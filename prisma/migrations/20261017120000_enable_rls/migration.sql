-- Turn on row level security for every table the app has.
--
-- Supabase publishes the public schema through its Data API (PostgREST), which
-- anyone holding the project's anon key can call. Without RLS every table here
-- (ledgers, users, sign-in sessions) can be read and written that way.
--
-- The app never uses the Data API. It reaches Postgres through Prisma as the
-- owner of these tables, and RLS does not apply to a table's owner (nothing here
-- says FORCE); it reaches file storage with the service key. So enabling RLS
-- with no policies shuts the Data API out and changes nothing for the app.
--
-- A table added by a later migration needs the same statement. The test
-- "every table has row level security" in tests/migration-safety.test.ts
-- fails until it has one.

